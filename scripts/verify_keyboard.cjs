const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const base=process.argv[2]||'http://127.0.0.1:8093';
assert(['localhost','127.0.0.1'].includes(new URL(base).hostname));
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'msedge'});
 const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
 const page=await context.newPage();
 await page.goto(base+'/');
 await page.keyboard.press('Tab');
 assert.equal(await page.locator(':focus').innerText(),'Zum Inhalt');
 await page.keyboard.press('Enter');
 const menu=page.locator('.nav-toggle');await menu.focus();await page.keyboard.press('Space');
 assert.equal(await menu.getAttribute('aria-expanded'),'true');await page.keyboard.press('Escape');
 assert.equal(await menu.getAttribute('aria-expanded'),'false');assert.equal(await page.locator(':focus').getAttribute('class'),'nav-toggle');
 await page.goto(base+'/buchen');
 await page.getByRole('button',{name:'Nächster Monat',exact:true}).focus();await page.keyboard.press('Enter');
 const day=page.locator('button.cal-day:not(:disabled)').nth(5);await day.focus();await page.keyboard.press('Enter');
 assert.equal(await page.locator('.cal-day:focus').getAttribute('aria-pressed'),'true');
 const slot=page.locator('.slot-btn').first();await slot.waitFor();await slot.focus();await page.keyboard.press('Enter');
 assert.equal(await slot.getAttribute('aria-pressed'),'true');assert(await page.locator('#booking-details').isVisible());
 const home=page.locator('#home-visit');await home.focus();await page.keyboard.press('Space');
 assert(await page.locator('#guest-address').isVisible());assert.equal(await page.locator('#guest-street').getAttribute('required'),'');
 await page.keyboard.press('Space');assert(!(await page.locator('#guest-address').isVisible()));
 console.log('PASS: skip link, mobile menu, Escape, calendar/slot keyboard selection and conditional address fields');
 const login=await context.request.post(base+'/api/auth/login',{headers:{Origin:base},data:{email:'preview@example.test',password:'preview-local-only'}});assert(login.ok());
 await page.goto(base+'/admin/appointments');
 const trigger=page.getByRole('button',{name:'Stornieren',exact:true}).first();await trigger.focus();await page.keyboard.press('Enter');
 const dialog=page.getByRole('dialog',{name:'Termin stornieren',exact:true});await dialog.waitFor();
 assert(await page.locator('#cancel-suggest-1:focus').count());
 await page.keyboard.press('Shift+Tab');assert.equal(await page.locator(':focus').innerText(),'Stornieren & Senden');
 await page.keyboard.press('Tab');assert(await page.locator('#cancel-suggest-1:focus').count());
 await page.keyboard.press('Escape');assert(!(await dialog.isVisible()));assert.equal(await page.locator(':focus').innerText(),'Stornieren');
 console.log('PASS: dialog initial focus, Tab containment, Escape and restored trigger focus');
 await page.goto(base+'/portal/profile');
 await page.evaluate(()=>document.documentElement.style.fontSize='200%');
 assert(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)));
 assert(await page.getByLabel('Vorname *',{exact:true}).isVisible());
 console.log('PASS: profile text at 200% remains readable with no horizontal page overflow');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
